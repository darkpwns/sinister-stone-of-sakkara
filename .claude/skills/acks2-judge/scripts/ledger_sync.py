#!/usr/bin/env python3
"""ledger_sync.py: rewrite the Ledger's "Purchases and sales" table from the inventory log (engine stage 6).

Every coin that moved through the inventory (purchases, sales, payments, receipts, wages, payout shares, exchanges)
is one row, generated by `acks.sh inv ledger --md`; the table is never edited by hand. Run by save.sh.
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jlib  # noqa: E402

HEAD = "| Date (game) | Where | Item | Qty | gp in | gp out | Character |\n| --- | --- | --- | --- | --- | --- | --- |"


def main():
    cfg = jlib.config()
    led = jlib.path(cfg["paths"]["state"].get("ledger", "Campaign/Ledger.md"))
    acks = os.path.join(os.path.dirname(os.path.abspath(__file__)), "acks.sh")
    r = subprocess.run(["bash", acks, "inv", "ledger", "--md"], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout + r.stderr)
        return 1
    rows = [x for x in r.stdout.splitlines() if x.startswith("|")]
    text = open(led, encoding="utf-8").read()
    m = re.search(r"(## Purchases and sales\n)(.*?)(?=\n## |\Z)", text, re.S)
    if not m:
        print(f"{led}: no '## Purchases and sales' section")
        return 1
    body = ("\nGenerated from the inventory log (`acks.sh inv ledger --md`) by save.sh; never edited by hand.\n\n" + HEAD
            + ("\n" + "\n".join(rows) if rows else "") + "\n")
    new = text[:m.start(2)] + body + text[m.end(2):]
    if new != text:
        with open(led, "w", encoding="utf-8") as f:
            f.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
